"""The shared-TCP frpc scene generates a HAProxy config, so check the text.

Only `--dry-run` is exercised: it prints the generated configuration and the
tmux commands without needing tmux, frpc or haproxy, which makes the routing
decision testable on a development machine.
"""

from pathlib import Path
import os
import shutil
import socket
import subprocess
import tempfile
import unittest


ROOT = Path(__file__).resolve().parents[1]
SCENE = ROOT / "scripts" / "scenes" / "frpc-shared-tcp.sh"
SH = shutil.which("sh")

FAKE_PEM = (
    "-----BEGIN CERTIFICATE-----\nMIIB\n-----END CERTIFICATE-----\n"
    "-----BEGIN PRIVATE KEY-----\nMIIE\n-----END PRIVATE KEY-----\n"
)
CERT_ONLY_PEM = "-----BEGIN CERTIFICATE-----\nMIIB\n-----END CERTIFICATE-----\n"
MUX_BEDROCK = "    server geyser 127.0.0.1:19132"
MUX_JAVA = "    server paper 127.0.0.1:25565"
MUX_LISTEN_PLAIN = "    bind 127.0.0.1:25566"
MUX_JAVA_PROXY = "    server paper 127.0.0.1:25565 send-proxy-v2"


@unittest.skipIf(SH is None, "POSIX sh is not available")
class SharedTcpSceneTests(unittest.TestCase):
    def setUp(self):
        self.temporary = tempfile.TemporaryDirectory()
        self.addCleanup(self.temporary.cleanup)
        self.directory = Path(self.temporary.name)
        self.configs = self.directory / "configs"
        self.configs.mkdir()
        (self.configs / "frpc.toml").write_text("serverAddr = 'example.org'\n", encoding="utf-8")

    def pem(self, name, content=FAKE_PEM):
        path = self.directory / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        return path

    def run_scene(self, *arguments, env=None):
        environment = dict(os.environ)
        environment.update(env or {})
        return subprocess.run(
            [SH, SCENE.as_posix(), "up", "--config", self.configs.as_posix(), *arguments],
            cwd=ROOT, capture_output=True, text=True, env=environment,
        )

    def manifest(self, text, name="the.scene"):
        path = self.configs / name
        with open(path, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(text)
        return path

    def run_manifest(self, scene, *arguments):
        return subprocess.run(
            [SH, SCENE.as_posix(), "up", "--scene", scene.as_posix(), *arguments],
            cwd=ROOT, capture_output=True, text=True,
        )

    def executable(self, directory, name, text):
        path = directory / name
        path.write_text(text, encoding="utf-8")
        path.chmod(0o755)
        return path

    def config(self, *arguments, env=None):
        """Return the generated HAProxy config lines from a dry run."""
        result = self.run_scene("--dry-run", *arguments, env=env)
        self.assertEqual(0, result.returncode, result.stderr)
        lines = result.stdout.splitlines()
        start = lines.index("# Generated by scripts/scenes/frpc-shared-tcp.sh; edits are overwritten.")
        config = []
        for line in lines[start + 1:]:
            if line.startswith("tmux "):
                break
            config.append(line)
        self.assertIn("frontend mc_shared", config)
        return config

    def assert_rejected(self, *arguments, env=None):
        result = self.run_scene(*arguments, env=env)
        self.assertEqual(2, result.returncode, result.stdout)
        self.assertIn("ERROR:", result.stderr)
        self.assertNotIn("Traceback", result.stderr)
        return result.stderr

    def test_plain_config_demuxes_only(self):
        config = self.config()
        self.assertIn("    mode tcp", config)
        self.assertIn("    use_backend geyser_signaling if is_tls or is_http", config)
        self.assertIn(MUX_BEDROCK, config)
        self.assertIn(MUX_JAVA, config)
        self.assertIn("    default_backend java", config)
        self.assertNotIn("geyser_tls", "\n".join(config))

    def test_a_scene_and_configs_are_mutually_exclusive(self):
        scene = self.manifest(
            "session = asp-frpc-shared\n"
            "server = true\n"
            "[udp]\nbinary = frpc\nconfig = frpc.toml\n"
        )

        result = subprocess.run(
            [SH, SCENE.as_posix(), "up", "--scene", scene.as_posix(),
             "--config", self.configs.as_posix(), "--dry-run"],
            cwd=ROOT, capture_output=True, text=True,
        )

        self.assertEqual(2, result.returncode, result.stdout)
        self.assertIn("mutually exclusive", result.stderr)

    def test_a_scene_keeps_the_three_sidecars_before_the_server(self):
        """Two TCP entries and the UDP media tunnel; the server is still last."""
        for name in ("entry-a.toml", "entry-b.toml", "udp.toml"):
            (self.configs / name).write_text("# frpc\n", encoding="utf-8")
        scene = self.manifest(
            "session = asp-frpc-shared\n"
            "server = true\n"
            "\n"
            "[entry_a]\nbinary = frpc\nconfig = entry-a.toml\n"
            "[entry_b]\nbinary = frpc\nconfig = entry-b.toml\n"
            "[udp]\nbinary = frpc\nconfig = udp.toml\n"
        )

        result = self.run_manifest(scene, "--dry-run")

        self.assertEqual(0, result.returncode, result.stderr)
        output = result.stdout
        sidecars = [output.index(f"-n frpc-{name}")
                    for name in ("entry_a", "entry_b", "udp")]
        mux = output.index("-n mux")
        server = output.index("bash scripts/start.sh")
        self.assertEqual(3, len(sidecars), output)
        self.assertLess(max(sidecars), mux, "every sidecar starts before the mux")
        self.assertLess(mux, server, "the mux starts before the server")
        self.assertIn("# server deferred", output)

    def test_an_invalid_scene_keeps_the_parser_exit_status(self):
        """The wrapper must not turn a manifest error (2) into a runtime error."""
        stubs = self.directory / "stubs"
        stubs.mkdir()
        self.executable(
            stubs, "tmux",
            "#!/bin/sh\n"
            "case \"$1\" in\n"
            "    has-session) exit 1 ;;\n"
            "esac\n"
            "exit 0\n",
        )
        haproxy = self.executable(stubs, "haproxy", "#!/bin/sh\nexit 0\n")
        scene = self.manifest(
            "session = asp-frpc-shared\n"
            "server = false\n"
            "[udp]\nbinary = frpc\n"
        )
        haproxy_config = self.directory / "haproxy.cfg"
        haproxy_config.write_text("# test config\n", encoding="utf-8")
        with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as listener:
            listener.bind(("127.0.0.1", 0))
            port = listener.getsockname()[1]

        environment = dict(os.environ)
        environment.update({
            "PATH": os.pathsep.join([stubs.as_posix(), environment["PATH"]]),
            "HAPROXY": haproxy.as_posix(),
            "MUX_PIDFILE": (self.directory / "haproxy.pid").as_posix(),
        })
        result = subprocess.run(
            [
                SH, SCENE.as_posix(), "up", "--scene", scene.as_posix(),
                "--haproxy-config", haproxy_config.as_posix(),
                "--listen", f"127.0.0.1:{port}",
            ],
            cwd=ROOT, capture_output=True, text=True, env=environment,
        )

        self.assertEqual(2, result.returncode, result.stdout + result.stderr)
        self.assertIn("section [udp] needs a config", result.stderr)
        self.assertIn("frpc scene failed to start", result.stderr)
        self.assertNotIn("Traceback", result.stderr)

    def test_proxy_protocol_accepts_the_header_and_hands_it_to_java(self):
        """R1: only the shared bind and the Java server line move."""
        config = self.config("--proxy-protocol")

        self.assertIn("    bind 127.0.0.1:25566 accept-proxy", config)
        self.assertIn(MUX_JAVA_PROXY, config)
        # The demux still classifies the same way, and the plain bind and the
        # signalling backend are untouched: the header is consumed by HAProxy
        # before tcp-request content, so the sniffing sees the real payload.
        self.assertNotIn(MUX_LISTEN_PLAIN, config)
        self.assertIn("    use_backend geyser_signaling if is_tls or is_http", config)
        self.assertIn(MUX_BEDROCK, config)
        moved = [
            line for line in config
            if ("accept-proxy" in line or "send-proxy-v2" in line)
        ]
        self.assertEqual(
            ["    bind 127.0.0.1:25566 accept-proxy", MUX_JAVA_PROXY], moved,
        )

    def test_proxy_protocol_with_a_certificate_still_terminates_tls(self):
        certificate = self.pem("certs/site.pem")

        config = self.config("--proxy-protocol", "--tls-cert", certificate.as_posix())

        # The switch is independent of TLS termination: the terminating bind
        # carries no header of its own (it is HAProxy talking to HAProxy on
        # loopback) and the signalling split is unchanged.
        self.assertIn("    bind 127.0.0.1:25566 accept-proxy", config)
        self.assertIn(MUX_JAVA_PROXY, config)
        self.assertIn("    use_backend geyser_tls if is_tls", config)
        self.assertIn("    use_backend geyser_signaling if is_http", config)
        listener = [line for line in config if line.startswith("    bind 127.0.0.1:25567 ssl crt ")]
        self.assertEqual(1, len(listener), config)
        self.assertNotIn("accept-proxy", listener[0])

    def test_proxy_protocol_takes_no_value(self):
        # The switch is boolean: `--proxy-protocol=x` is not it, and the
        # unknown-option path refuses it before anything is started.
        for value in ["--proxy-protocol=x", "--proxy-protocol=true"]:
            with self.subTest(value=value):
                errors = self.assert_rejected(value)
                self.assertIn("unknown up option", errors)
                self.assertIn(value, errors)

    def test_proxy_protocol_cannot_swallow_the_next_option(self):
        # The switch may be placed anywhere among the others: it never
        # consumes the option that follows it.
        config = self.config("--proxy-protocol", "--java", "127.0.0.1:25570")

        self.assertIn("    bind 127.0.0.1:25566 accept-proxy", config)
        self.assertIn("    server paper 127.0.0.1:25570 send-proxy-v2", config)

    def test_proxy_protocol_adds_lan_java_by_default(self):
        config = self.config("--proxy-protocol")

        self.assertIn("frontend lan_java", config)
        self.assertIn("    bind 0.0.0.0:25564", config)
        self.assertIn("    default_backend java", config)
        self.assertIn(MUX_JAVA_PROXY, config)
        lan = config[config.index("frontend lan_java"):]
        self.assertNotIn("accept-proxy", "\n".join(lan))

    def test_lan_java_bind_can_be_overridden(self):
        config = self.config(
            "--proxy-protocol",
            env={"MUX_LAN_JAVA": "192.168.50.10:26064"},
        )
        self.assertIn("    bind 192.168.50.10:26064", config)
        self.assertNotIn("    bind 0.0.0.0:25564", config)

    def test_a_hand_written_config_keeps_owning_the_whole_file(self):
        haproxy_config = self.configs / "haproxy.cfg"
        haproxy_config.write_text("# test config\n", encoding="utf-8")

        result = self.run_scene(
            "--dry-run", "--proxy-protocol",
            "--haproxy-config", haproxy_config.as_posix(),
        )

        self.assertEqual(0, result.returncode, result.stderr)
        self.assertIn("would use HAProxy config", result.stdout)
        self.assertNotIn("frontend lan_java", result.stdout)

    def test_lan_java_must_differ_from_every_other_bind(self):
        for endpoint in [
            "127.0.0.1:25566",
            "127.0.0.1:25565",
            "127.0.0.1:19132",
            "0.0.0.0:25565",
        ]:
            with self.subTest(endpoint=endpoint):
                errors = self.assert_rejected(
                    "--proxy-protocol",
                    env={"MUX_LAN_JAVA": endpoint},
                )
                self.assertIn("must differ", errors)

    def test_lan_java_must_be_an_endpoint(self):
        errors = self.assert_rejected(
            "--proxy-protocol",
            env={"MUX_LAN_JAVA": "25564"},
        )
        self.assertIn("HOST:PORT", errors)

    def test_lan_java_must_differ_from_the_tls_listener(self):
        certificate = self.pem("certs/site.pem")

        errors = self.assert_rejected(
            "--proxy-protocol",
            "--tls-cert", certificate.as_posix(),
            "--tls-listen", "127.0.0.1:25564",
            env={"MUX_LAN_JAVA": "127.0.0.1:25564"},
        )

        self.assertIn("--tls-listen must differ from MUX_LAN_JAVA", errors)

    def test_plain_config_is_unchanged(self):
        self.assertEqual(
            [
                "# Java and Bedrock built-in signalling share this local TCP port.",
                "global",
                "    maxconn 4096",
                "",
                "defaults",
                "    mode tcp",
                "    timeout connect 5s",
                "    timeout client 1h",
                "    timeout server 1h",
                "",
                "frontend mc_shared",
                "    bind 127.0.0.1:25566",
                "    acl is_tls req.ssl_hello_type 1",
                '    acl is_http payload(0,4) -m beg "GET " "POST" "HEAD" "PUT " "OPTI" "PATC" "DELE" "CONN" "TRAC" "PRI "',
                "    acl is_java payload(0,1) -m bin fe",
                "    acl is_java payload(1,1) -m bin 00",
                "    tcp-request inspect-delay 3s",
                "    tcp-request content accept if is_tls or is_http or is_java",
                "    use_backend geyser_signaling if is_tls or is_http",
                "    default_backend java",
                "",
                "backend geyser_signaling",
                MUX_BEDROCK,
                "",
                "backend java",
                MUX_JAVA,
            ],
            self.config(),
        )

    def test_tls_cert_adds_a_terminating_frontend(self):
        certificate = self.pem("certs/site.pem")
        config = self.config("--tls-cert", certificate.as_posix())
        text = "\n".join(config)
        self.assertIn("    use_backend geyser_tls if is_tls", config)
        self.assertIn("    use_backend geyser_signaling if is_http", config)
        self.assertIn("    default_backend java", config)
        # Plain HTTP keeps its direct route to Geyser; only the ClientHello
        # is handed to the terminating frontend.
        self.assertNotIn("geyser_signaling if is_tls", text)
        self.assertIn("backend geyser_tls", config)
        self.assertIn("    server termination 127.0.0.1:25567", config)
        self.assertIn("frontend geyser_tls_termination", config)
        self.assertIn(MUX_BEDROCK, config)
        self.assertIn(MUX_JAVA, config)
        listener = [line for line in config if line.startswith("    bind 127.0.0.1:25567 ssl crt ")]
        self.assertEqual(1, len(listener), config)
        self.assertTrue(listener[0].endswith("site.pem"), listener[0])

    def test_tls_listen_can_be_moved(self):
        certificate = self.pem("certs/site.pem")
        config = self.config("--tls-cert", certificate.as_posix(), "--tls-listen", "127.0.0.1:26000")
        self.assertIn("    server termination 127.0.0.1:26000", config)
        self.assertIn("    bind 127.0.0.1:26000 ssl crt ", "\n".join(config))
        self.assertNotIn("25567", "\n".join(config))

    def test_endpoint_overrides_reach_the_terminating_frontend(self):
        certificate = self.pem("certs/site.pem")
        config = self.config(
            "--tls-cert", certificate.as_posix(), "--bedrock", "127.0.0.1:19133",
            "--java", "127.0.0.1:25570",
        )
        self.assertIn("    server geyser 127.0.0.1:19133", config)
        self.assertIn("    server paper 127.0.0.1:25570", config)

    def terminating_bind(self, config):
        """The one bind that terminates TLS, and nothing else."""
        listener = [line for line in config if line.startswith("    bind ") and " ssl " in line]
        self.assertEqual(1, len(listener), config)
        return listener[0]

    def test_two_certificates_share_the_terminating_bind(self):
        """SNI picks between them, so several names can share one port."""
        first = self.pem("certs/aaa.nyat.app.pem")
        second = self.pem("certs/bbb.nyat.app.pem")

        config = self.config(
            "--tls-cert", first.as_posix(), "--tls-cert", second.as_posix(),
        )

        listener = self.terminating_bind(config)
        self.assertEqual(2, listener.count(" crt "), listener)
        self.assertLess(listener.index("aaa.nyat.app.pem"), listener.index("bbb.nyat.app.pem"),
                        "the order the operator gave is kept")
        self.assertIn("    # 2 names on one bind: HAProxy chooses the certificate by", config)
        self.assertNotIn("strict-sni", listener)

    def test_strict_sni_reaches_the_terminating_bind(self):
        certificate = self.pem("certs/site.pem")

        listener = self.terminating_bind(
            self.config("--tls-cert", certificate.as_posix(), "--strict-sni")
        )

        self.assertTrue(listener.endswith(" strict-sni"), listener)

    def test_strict_sni_without_a_certificate_is_rejected(self):
        errors = self.assert_rejected("--strict-sni")

        self.assertIn("--tls-cert", errors)

    def test_a_second_certificate_is_checked_like_the_first(self):
        good = self.pem("certs/good.pem")
        cert_only = self.pem("certs/cert-only.pem", CERT_ONLY_PEM)

        errors = self.assert_rejected(
            "--tls-cert", good.as_posix(), "--tls-cert", cert_only.as_posix(),
        )

        self.assertIn("private key", errors)

    def test_the_same_certificate_twice_is_rejected(self):
        certificate = self.pem("certs/site.pem")

        errors = self.assert_rejected(
            "--tls-cert", certificate.as_posix(), "--tls-cert", certificate.as_posix(),
        )

        self.assertIn("the same TLS certificate twice", errors)

    def test_certificate_path_with_spaces_is_quoted(self):
        certificate = self.pem("certs/with space.pem")
        config = self.config("--tls-cert", certificate.as_posix())
        listener = [line for line in config if "ssl crt " in line]
        self.assertEqual(1, len(listener), config)
        self.assertTrue(listener[0].endswith('with space.pem"'), listener[0])
        self.assertIn('ssl crt "', listener[0])

    def test_missing_certificate_is_rejected(self):
        self.assert_rejected("--tls-cert", (self.directory / "nope.pem").as_posix())

    def test_certificate_without_a_private_key_is_rejected(self):
        certificate = self.pem("certs/cert-only.pem", CERT_ONLY_PEM)
        errors = self.assert_rejected("--tls-cert", certificate.as_posix())
        self.assertIn("private key", errors)

    def test_file_that_is_not_a_pem_is_rejected(self):
        certificate = self.pem("certs/junk.pem", "not a certificate\n")
        errors = self.assert_rejected("--tls-cert", certificate.as_posix())
        self.assertIn("no PEM certificate", errors)

    def test_directory_instead_of_certificate_is_rejected(self):
        directory = self.directory / "certs"
        directory.mkdir()
        self.assert_rejected("--tls-cert", directory.as_posix())

    def test_tls_listen_without_a_certificate_is_rejected(self):
        errors = self.assert_rejected("--tls-listen", "127.0.0.1:25567")
        self.assertIn("--tls-cert", errors)

    def test_tls_certificate_with_a_hand_written_config_is_rejected(self):
        certificate = self.pem("certs/site.pem")
        self.assert_rejected(
            "--tls-cert", certificate.as_posix(),
            "--haproxy-config", (self.configs / "frpc.toml").as_posix(),
        )

    def test_tls_listen_may_not_collide_with_the_other_endpoints(self):
        certificate = self.pem("certs/site.pem")
        for endpoint in ["127.0.0.1:25566", "127.0.0.1:25565", "127.0.0.1:19132"]:
            with self.subTest(endpoint=endpoint):
                errors = self.assert_rejected(
                    "--tls-cert", certificate.as_posix(), "--tls-listen", endpoint,
                )
                self.assertIn("must differ", errors)

    def test_tls_listen_must_be_an_endpoint(self):
        certificate = self.pem("certs/site.pem")
        errors = self.assert_rejected(
            "--tls-cert", certificate.as_posix(), "--tls-listen", "25567",
        )
        self.assertIn("HOST:PORT", errors)


if __name__ == "__main__":
    unittest.main()
