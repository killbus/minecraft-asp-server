        (self.directory / "a" / "packs").mkdir()
        script = scenes / "frpc-shared-tcp.sh"
        shutil.copy2(SCENE, script)
        frpc = scenes / "frpc.sh"
        frpc.write_text("#!/bin/sh\nexit 0\n", encoding="utf-8")
        frpc.chmod(0o755)
        environment = dict(os.environ)
