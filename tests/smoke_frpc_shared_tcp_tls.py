#!/usr/bin/env python3
"""Smoke-test the TLS-terminating frpc shared-TCP scene on a real HAProxy.

Run this on the Linux host that runs the scene:

    python3 tests/smoke_frpc_shared_tcp_tls.py

It needs `sh`, `haproxy` and `openssl` on PATH. tmux, frpc and NATFRP are not
involved: the script generates a throwaway certificate, starts two throwaway
loopback backends, builds the HAProxy configuration through the scene's own
--dry-run, and then checks that

  * HAProxy accepts the generated configuration (`haproxy -c -f`),
  * the TLS frontend presents the certificate for the SNI it was asked for,
  * a TLS ClientHello on the shared port reaches the signalling backend,
  * plain HTTP on the shared port still reaches the signalling backend,
  * Java bytes on the shared port reach the Java backend.

The whole run then repeats with the scene's `--proxy-protocol`: the shared
port is then bound with `accept-proxy`, so every client says what frpc says -
a PROXY protocol v2 header - and this run sends one. It covers both the
`send-proxy-v2` half (Java still reaches the backend) and the `accept-proxy`
half (a headerless connection is refused).

Exit codes: 0 every check passed, 1 a check failed or a tool is missing,
2 bad usage.
"""

import argparse
from http.server import BaseHTTPRequestHandler
from pathlib import Path
import signal
import shutil
import socket
import socketserver
import ssl
import struct
import subprocess
import sys
import tempfile
import threading
import time


ROOT = Path(__file__).resolve().parents[1]
SCENE = ROOT / "scripts" / "scenes" / "frpc-shared-tcp.sh"
CONFIG_HEADER = "# Generated by scripts/scenes/frpc-shared-tcp.sh; edits are overwritten."
CERT_NAME = "asp-smoke.example.test"
JAVA_REPLY = b"JAVA-BACKEND\n"
HTTP_BODY = b"GEYSER-HTTP\n"
# The PROXY v2 signature the probe script writes too; the header is built
# from it so both ends of the deployment agree on the bytes.
PROXY_V2_SIGNATURE = b"\r\n\r\n\x00\r\nQUIT\n"
# What a real client through frpc arrives as: the peer address frpc names,
# which Paper prints in the login line. The port is arbitrary; nothing here
# asserts on the address itself.
PROXY_SOURCE = ("203.0.113.7", 40777)


def require(tool):
    try:
        result = subprocess.run(
            ["sh", "-c", f"command -v {tool}"], capture_output=True, text=True
        )
    except FileNotFoundError:
        print("FAIL: no POSIX sh on PATH")
        sys.exit(1)
    path = result.stdout.strip()
    if result.returncode != 0 or not path:
        print(f"FAIL: {tool} is not on PATH")
        sys.exit(1)
    return path


def free_port(taken):
    while True:
        with socket.socket() as probe:
            probe.bind(("127.0.0.1", 0))
            port = probe.getsockname()[1]
        if port not in taken:
            taken.add(port)
            return port


class CountingServer(socketserver.ThreadingTCPServer):
    allow_reuse_address = True
    daemon_threads = True

    def __init__(self, address, handler):
        super().__init__(address, handler)
        self.connections = 0
        self.lock = threading.Lock()

    def count(self):
        with self.lock:
            self.connections += 1


class JavaHandler(socketserver.BaseRequestHandler):
    def handle(self):
        self.server.count()
        # Java opens with either a legacy ping (0xFE) or a handshake (0x00).
        self.request.recv(64)
        self.request.sendall(JAVA_REPLY)


class GeyserHandler(BaseHTTPRequestHandler):
    protocol_version = "HTTP/1.1"

    def do_GET(self):
        self.server.count()
        self.send_response(200)
        self.send_header("Content-Type", "text/plain")
        self.send_header("Content-Length", str(len(HTTP_BODY)))
        self.end_headers()
        self.wfile.write(HTTP_BODY)

    def log_message(self, *args):
        pass


def start_server(server):
    thread = threading.Thread(target=server.serve_forever, daemon=True)
    thread.start()
    return thread


def wait_for_port(port, timeout=10.0):
    deadline = time.monotonic() + timeout
    while time.monotonic() < deadline:
        try:
            with socket.create_connection(("127.0.0.1", port), 0.5):
                return True
        except OSError:
            time.sleep(0.1)
    return False


def make_certificate(directory, openssl):
    certificate = directory / "cert.pem"
    key = directory / "key.pem"
    base = [
        openssl, "req", "-x509", "-newkey", "rsa:2048", "-nodes", "-days", "2",
        "-subj", f"/CN={CERT_NAME}", "-keyout", str(key), "-out", str(certificate),
    ]
    result = subprocess.run(
        base + ["-addext", f"subjectAltName=DNS:{CERT_NAME}"],
        capture_output=True, text=True,
    )
    if result.returncode != 0:
        # OpenSSL before 1.1.1 has no -addext; the smoke test passes a CAfile
        # and a matching SNI, so a SAN-less certificate is still enough.
        result = subprocess.run(base, capture_output=True, text=True)
    if result.returncode != 0:
        print("FAIL: openssl could not create the test certificate")
        print(result.stderr.strip())
        sys.exit(1)
    bundle = directory / "site.pem"
    bundle.write_bytes(certificate.read_bytes() + key.read_bytes())
    return certificate, bundle


def run_scene(directory, certificate, ports, sh, *extra):
    """Run the scene's --dry-run for one listen/java/bedrock/tls set."""
    config_dir = directory / "configs"
    config_dir.mkdir(exist_ok=True)
    (config_dir / "frpc.toml").write_text("serverAddr = 'example.org'\n", encoding="utf-8")
    return subprocess.run(
        [
            sh, SCENE.as_posix(), "up",
            "--config", config_dir.as_posix(),
            "--listen", f"127.0.0.1:{ports['listen']}",
            "--java", f"127.0.0.1:{ports['java']}",
            "--bedrock", f"127.0.0.1:{ports['bedrock']}",
            "--tls-cert", certificate.as_posix(),
            "--tls-listen", f"127.0.0.1:{ports['tls']}",
            "--dry-run", *extra,
        ],
        cwd=ROOT, capture_output=True, text=True,
    )


def generate_haproxy_config(directory, certificate, ports, sh, name, *extra):
    result = run_scene(directory, certificate, ports, sh, *extra)
    if result.returncode != 0:
        print("FAIL: the scene could not generate a configuration")
        print(result.stderr.strip())
        sys.exit(1)

    lines = result.stdout.splitlines()
    if CONFIG_HEADER not in lines:
        print("FAIL: the dry run printed no HAProxy configuration")
        print(result.stdout)
        sys.exit(1)
    generated = []
    for line in lines[lines.index(CONFIG_HEADER) + 1:]:
        if line.startswith("tmux "):
            break
        generated.append(line)
    config = directory / f"haproxy-{name}.cfg"
    config.write_text("\n".join(generated) + "\n", encoding="utf-8")
    return config


def check_haproxy_config(haproxy, config):
    result = subprocess.run([haproxy, "-c", "-f", str(config)], capture_output=True, text=True)
    if result.returncode != 0:
        print("FAIL: haproxy rejected the generated configuration")
        print((result.stdout + result.stderr).strip())
        sys.exit(1)
    return (result.stdout + result.stderr).strip() or "configuration is valid (no output)"


def proxy_v2_header(source, destination):
    """The PROXY protocol v2 header frpc writes ahead of a connection.

    Signature, version/command, family/protocol, the length of the address
    block, then the IPv4 addresses and ports. No checksum: `accept-proxy`
    does not require one.
    """
    addresses = (
        socket.inet_aton(source[0])
        + socket.inet_aton(destination[0])
        + struct.pack("!HH", source[1], destination[1])
    )
    return PROXY_V2_SIGNATURE + b"\x21\x11" + struct.pack("!H", len(addresses)) + addresses


def connect(port, proxy):
    """Open the shared port, announcing the source first when it expects to."""
    connection = socket.create_connection(("127.0.0.1", port), 5)
    if proxy:
        connection.sendall(proxy_v2_header(PROXY_SOURCE, ("127.0.0.1", port)))
    return connection


def http_over_tls(port, certificate, proxy):
    context = ssl.create_default_context(cafile=str(certificate))
    context.check_hostname = True
    with connect(port, proxy) as raw:
        with context.wrap_socket(raw, server_hostname=CERT_NAME) as tls:
            tls.sendall(
                f"GET / HTTP/1.1\r\nHost: {CERT_NAME}\r\nConnection: close\r\n\r\n".encode()
            )
            response = b""
            while len(response) < 4096:
                chunk = tls.recv(4096)
                if not chunk:
                    break
                response += chunk
    return response


def http_plain(port, proxy):
    with connect(port, proxy) as plain:
        plain.sendall(
            f"GET / HTTP/1.1\r\nHost: {CERT_NAME}\r\nConnection: close\r\n\r\n".encode()
        )
        response = b""
        while len(response) < 4096:
            chunk = plain.recv(4096)
            if not chunk:
                break
            response += chunk
    return response


def java_legacy_ping(port, proxy):
    with connect(port, proxy) as plain:
        plain.sendall(b"\xfe\x01\xfa")
        return plain.recv(64)


def certificate_covers_name(presented):
    """True when the certificate names the host we asked for."""
    common_names = [
        value for entry in presented.get("subject", ()) for key, value in entry
        if key == "commonName"
    ]
    alt_names = [value for key, value in presented.get("subjectAltName", ()) if key == "DNS"]
    return CERT_NAME in common_names and (not alt_names or CERT_NAME in alt_names)


def check_certificate(port, certificate, proxy):
    """The terminating bind itself has to serve a certificate for the SNI.

    Verifying the handshake against the throwaway certificate covers the
    chain and the host name; the subject is asserted explicitly because
    `openssl s_client` is no good here - it exits non-zero when the peer
    closes without a close_notify.

    The TLS bind stays HAProxy-to-HAProxy on loopback, so it carries no
    header whatever the shared port was started with.
    """
    context = ssl.create_default_context(cafile=str(certificate))
    with socket.create_connection(("127.0.0.1", port), 5) as raw:
        with context.wrap_socket(raw, server_hostname=CERT_NAME) as tls:
            presented = tls.getpeercert()
    return certificate_covers_name(presented)


def check_tls_mux(port, certificate, proxy):
    response = http_over_tls(port, certificate, proxy)
    return response.startswith(b"HTTP/1.1 200") and HTTP_BODY in response


def check_plain_mux(port, proxy):
    response = http_plain(port, proxy)
    return response.startswith(b"HTTP/1.1 200") and HTTP_BODY in response


def check_java_mux(port, proxy):
    return java_legacy_ping(port, proxy) == JAVA_REPLY


def check_header_required(port):
    """A mux bound with `accept-proxy` refuses a connection without a header.

    A plain Java ping is exactly what such a client would send, and the mux
    must not answer it: HAProxy drops the connection at the bind, before any
    backend sees a byte.
    """
    try:
        with socket.create_connection(("127.0.0.1", port), 5) as plain:
            plain.sendall(b"\xfe\x01\xfa")
            return plain.recv(64) != JAVA_REPLY
    except OSError:
        return True


def run_round(name, proxy, directory, bundle, certificate, ports, sh, haproxy):
    """One HAProxy configuration and the checks that describe it.

    The plain round leaves every client alone; the PROXY round sends a PROXY
    protocol v2 header ahead of each connection and expects the mux to refuse
    the one connection that arrives without one.
    """
    print(f"== {name} run: the scene generates, HAProxy serves, "
          f"{'PROXY v2 headers' if proxy else 'no header'} ==")
    extra = ["--proxy-protocol"] if proxy else []
    config = generate_haproxy_config(directory, bundle, ports, sh, name, *extra)
    print(f"generated: {config}")
    print(f"haproxy -c: {check_haproxy_config(haproxy, config)}")

    checks = [
        (
            "certificate on the terminating bind",
            lambda: check_certificate(ports["tls"], certificate, proxy=False),
        ),
        (
            "TLS on the shared port reaches the signalling backend",
            lambda: check_tls_mux(ports["listen"], certificate, proxy),
        ),
        (
            "plain HTTP on the shared port reaches the signalling backend",
            lambda: check_plain_mux(ports["listen"], proxy),
        ),
        (
            "Java bytes on the shared port reach the Java backend",
            lambda: check_java_mux(ports["listen"], proxy),
        ),
    ]
    if proxy:
        checks.append(
            (
                "a headerless connection to the shared port is refused",
                lambda: check_header_required(ports["listen"]),
            )
        )

    log = (directory / f"haproxy-{name}.log").open("wb")
    process = subprocess.Popen(
        [haproxy, "-db", "-f", str(config)], stdout=log, stderr=subprocess.STDOUT,
    )
    log.close()
    try:
        if not wait_for_port(ports["listen"]):
            print("FAIL: the shared port never accepted connections")
            return 1
        failures = 0
        for check_name, check in checks:
            try:
                passed = check()
            except OSError as error:
                passed = False
                print(f"      {error}")
            print(f"{'ok  ' if passed else 'FAIL'} {check_name}")
            failures += 0 if passed else 1
        if failures:
            print(f"FAILED: {failures} check(s) - {name} run")
            print((directory / f"haproxy-{name}.log").read_text(errors="replace"))
            return 1
        return 0
    finally:
        process.send_signal(signal.SIGTERM)
        try:
            process.wait(5)
        except subprocess.TimeoutExpired:
            process.kill()


def main(argv):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--keep", action="store_true", help="keep the temporary directory")
    arguments = parser.parse_args(argv)

    sh = require("sh")
    haproxy = require("haproxy")
    openssl = require("openssl")
    if not SCENE.is_file():
        print(f"FAIL: cannot find {SCENE}")
        return 1

    temporary = tempfile.mkdtemp(prefix="asp-frpc-shared-smoke-")
    directory = Path(temporary)
    taken = set()
    ports = {name: free_port(taken) for name in ["listen", "java", "bedrock", "tls"]}
    print(f"work dir: {directory}")
    print("ports: " + ", ".join(f"{name}={port}" for name, port in ports.items()))

    servers = []
    try:
        certificate, bundle = make_certificate(directory, openssl)
        # These stand-ins never parse the PROXY header the mux forwards
        # (send-proxy-v2); reading it back is `proxies.proxy-protocol` on the
        # real Paper. What they check is unchanged - a Java byte string
        # reaches the Java backend - and that holds whether or not a header
        # sits in front of it. The header's own bytes are asserted in
        # tests/test_probe_public_entry.
        java_server = CountingServer(("127.0.0.1", ports["java"]), JavaHandler)
        geyser_server = CountingServer(("127.0.0.1", ports["bedrock"]), GeyserHandler)
        for server in [java_server, geyser_server]:
            servers.append(server)
            start_server(server)

        for name, proxy in [("plain", False), ("proxy", True)]:
            code = run_round(
                name, proxy, directory, bundle, certificate, ports, sh, haproxy,
            )
            print(
                f"backend connections: java={java_server.connections}, "
                f"signalling={geyser_server.connections} "
                "(each round's readiness probe stays unclassified until "
                "inspect-delay expires, so it may reach Java)"
            )
            if code != 0:
                return code

        print("PASS: the TLS-terminating shared-TCP scene works locally, "
              "with and without PROXY protocol v2")
        return 0
    finally:
        for server in servers:
            server.shutdown()
            server.server_close()
        if arguments.keep:
            print(f"kept: {directory}")
        elif directory.name.startswith("asp-frpc-shared-smoke-") and directory.is_dir():
            shutil.rmtree(directory, ignore_errors=True)


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
